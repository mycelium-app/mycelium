const ROUTER: &str = include_str!("../../src/lib.rs");
const COOLIFY: &str = include_str!("../../src/coolify.rs");
const METHODS: [&str; 6] = ["get", "post", "put", "patch", "delete", "any"];

fn routes() -> BTreeSet<(String, String)> {
    let mut found = BTreeSet::new();

    for (start, _) in ROUTER.match_indices(".route(") {
        let body = balanced(&ROUTER[start + ".route(".len()..]);
        let path = body.split('"').nth(1).expect("a route starts with its path");

        for method in METHODS {
            for (at, _) in body.match_indices(&format!("{method}(")) {
                let before = body[..at].chars().last().unwrap_or(' ');

                if !(before.is_alphanumeric() || before == '_') {
                    found.insert((method.to_uppercase(), path.to_string()));
                }
            }
        }
    }

    found
}

fn balanced(text: &str) -> &str {
    let mut depth = 1;

    for (at, character) in text.char_indices() {
        match character {
            '(' => depth += 1,
            ')' => {
                depth -= 1;

                if depth == 0 {
                    return &text[..at];
                }
            }
            _ => {}
        }
    }

    panic!("unbalanced route")
}

fn key(method: &str, path: &str) -> (String, String) {
    (method.to_string(), path.to_string())
}

#[test]
fn every_route_has_a_tool_or_a_reviewed_reason() {
    let routes = routes();
    let mut reviewed = BTreeSet::new();

    for (method, path, _) in COVERED.iter().chain(EXCEPTIONS) {
        assert!(reviewed.insert(key(method, path)), "{method} {path} is listed twice");
    }

    for (method, path) in NOT_YET_COVERED {
        assert!(reviewed.insert(key(method, path)), "{method} {path} is listed twice");
    }

    let missing: Vec<_> = routes.difference(&reviewed).collect();
    assert!(missing.is_empty(), "these routes have no MCP tool: add one, or list them in EXCEPTIONS with a reason: {missing:?}");

    let gone: Vec<_> = reviewed.difference(&routes).collect();
    assert!(gone.is_empty(), "these listed routes no longer exist: {gone:?}");
}

#[tokio::test]
async fn every_covering_tool_exists() {
    let server = Server::start().await;
    let (_, token) = server.join("node", "laptop").await;

    let anonymous = server.anonymous();
    let (_, listed): (u16, Value) = anonymous.json(anonymous.post("/api/v1/mcp").header("authorization", format!("Bearer {token}")).json(&json!({"jsonrpc": "2.0", "id": 1, "method": "tools/list"}))).await;
    let tools: BTreeSet<&str> = listed["result"]["tools"].as_array().unwrap().iter().map(|tool| tool["name"].as_str().unwrap()).collect();

    for (method, path, tool) in COVERED {
        let exists = match tool.strip_prefix("coolify__") {
            Some(name) => COOLIFY.contains(&format!("\"{name}\"")),
            None => tools.contains(tool),
        };

        assert!(exists, "{method} {path} names {tool}, which is not a tool");
    }
}

